// npm run build:demo
// Runs both example campaigns through the real code (example Claude output, pretend Upload-Post)
// and writes docs/data.js for the demo page.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { getConfig } from "../src/config.js";
import { runDraft, runSchedule } from "../src/pipeline.js";
import { loadDrafts } from "../src/drafts.js";
import { calendarEntries } from "../src/calendar.js";
import { stats } from "../src/rules.js";
import { EXAMPLES, DEMO_NOW, setupExample, fakeUploadPost } from "./examples.js";

const out = { now: DEMO_NOW.toISOString(), examples: {} };
for (const name of EXAMPLES) {
  const ex = setupExample(name);
  const config = { ...getConfig({}), root: ex.root, uploadPostProfile: "your-profile" };
  const draft = await runDraft({ ...ex, config, now: DEMO_NOW, log: () => {} });
  const drafts = loadDrafts(ex.root, ex.rules);
  const before = calendarEntries({ drafts, state: { posts: {} }, brand: ex.brand, rules: ex.rules, media: ex.media, now: DEMO_NOW, mode: "draft" });
  const client = fakeUploadPost();
  const { report, state } = await runSchedule({ ...ex, config, client, now: DEMO_NOW, log: () => {} });
  const after = calendarEntries({ drafts: loadDrafts(ex.root, ex.rules), state, brand: ex.brand, rules: ex.rules, media: ex.media, now: DEMO_NOW, mode: "main" });
  const requests = {};
  for (const r of client.requests) {
    const f = Object.fromEntries(r.fields);
    requests[f.external_id.replace("signalpost-ref:", "").replace(/:([a-z]+)$/, ":$1")] = { endpoint: r.endpoint, fields: r.fields, files: r.attachments.map((a) => `${a.field} = ${a.name}`), idempotencyKey: r.headers["Idempotency-Key"] };
  }
  out.examples[name] = {
    brand: { name: ex.brand.name, timezone: ex.brand.timezone, networks: ex.brand.networks, plan: ex.brand.plan, links: ex.brand.links, voice: ex.brand.voice },
    brandFile: readFileSync(join(ex.root, "brand.md"), "utf8"),
    plan: readFileSync(join(ex.root, "plan.md"), "utf8"),
    media: Object.values(ex.media).map(({ name: n, kind, width, height, duration, ratio, shape }) => ({ name: n, kind, width, height, duration, ratio, shape })),
    posts: draft.results.map((r) => ({
      ref: r.item.ref, label: r.item.label, format: r.item.format, media: r.item.media, date: r.item.date, time: r.item.time, timezone: r.item.timezone,
      status: r.item.status, question: r.item.question, source: r.item.source, confidence: r.item.confidence, file: r.file,
      networks: r.item.networks.map((n) => ({ id: n, ...r.posts[n], issues: r.issues[n], stats: stats(n, r.posts[n], r.item, ex.rules) })),
      fixes: r.fixes, markdown: readFileSync(join(ex.root, r.file), "utf8"),
    })),
    suspicious: draft.suspicious, dropped: draft.dropped,
    summary: draft.summary,
    before, after,
    report: { scheduled: report.scheduled, skipped: report.skipped, monthly: report.monthly },
    requests,
    calendarMd: readFileSync(join(ex.root, "CALENDAR.md"), "utf8"),
    ics: readFileSync(join(ex.root, "calendar.ics"), "utf8"),
  };
}
const rules = JSON.parse(readFileSync(new URL("../rules/networks.json", import.meta.url), "utf8"));
out.rules = rules;
writeFileSync(new URL("../docs/data.js", import.meta.url), `// Generated by scripts/build-demo.js. Do not edit by hand.\nwindow.SIGNALPOST = ${JSON.stringify(out)};\n`);
console.log(`Wrote docs/data.js: ${EXAMPLES.map((e) => `${e} ${out.examples[e].posts.length} posts / ${out.examples[e].report.scheduled.length} scheduled`).join(", ")}.`);
